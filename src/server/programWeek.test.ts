// Run: tsx src/server/programWeek.test.ts
// 2026-11-12, replayed on a scratch database (made-up data, his shape): a
// Block Zero that started weeks ago with nothing key done, so the week counter
// waits and this week and next are both week 1. The week is first opened on a
// Wednesday, and next week's plan is made (empty) that night.
// - Program reads this calendar week's sessions, not next week's empty plan.
// - The week built on Wednesday plans from Wednesday: no Monday or Tuesday
//   sessions, and no missed rows made for them after the fact.
import assert from 'node:assert/strict'
import { and, eq, gte, lte } from 'drizzle-orm'
import { createDB } from '../db/client'
import { sessions, settings, trainingBlocks, userProfile, weekPlans } from '../db/schema'
import { isoToEpochDay, TODAY_HEADER } from '../lib/dates'
import { startedAtForLocalDay } from '../lib/coach'
import { createTrainingBlock } from './blocks'
import { backfillCurrentWeek, resolveWeekPlan } from './coachData'
import { migratedSqlite } from './replay/db'
import { d1Shim } from './replay/d1Shim'
import { installClock, uninstallClock } from './replay/clock'

const START = isoToEpochDay('2026-10-30') // a Friday, weeks ago
const MON = isoToEpochDay('2026-11-09')
const WED = MON + 2
const THU = MON + 3

installClock(Date.UTC(2026, 10, 11, 17, 0))
try {
  const app = (await import('./app')).default
  const env = { DB: d1Shim(migratedSqlite(':memory:')), WAYMARK_API_KEY: 'k', ANTHROPIC_API_KEY: '' }
  const db = createDB(env as never)
  const ctx = { waitUntil() {}, passThroughOnException() {}, props: {} }
  const call = async <T>(today: string, method: string, path: string, body?: unknown): Promise<T> => {
    const res = await app.fetch(new Request(`http://local${path}`, {
      method, headers: { Authorization: 'Bearer k', [TODAY_HEADER]: today, ...(body ? { 'Content-Type': 'application/json' } : {}) },
      ...(body ? { body: JSON.stringify(body) } : {}),
    }), env as never, ctx as never)
    assert.equal(res.status, 200, `${method} ${path}: ${res.status}`)
    return res.json() as Promise<T>
  }
  await db.insert(settings).values({ id: 'default', mtClassDays: '', createdAt: 1, updatedAt: 1 }).onConflictDoNothing()
  await db.insert(userProfile).values({ id: 'default', dob: '1990-04-01', createdAt: 1, updatedAt: 1 }).onConflictDoNothing()
  await createTrainingBlock(db, { name: 'Block Zero', blockType: 'block_zero', totalWeeks: 6, nowSec: START * 86400, startedAt: startedAtForLocalDay(START) })
  const [block] = await db.select().from(trainingBlocks)

  // Wednesday: he opens the app; the week is built and today is made.
  await call('2026-11-11', 'POST', '/api/sessions/generate-today', { date: '2026-11-11' })
  // That night: next week's plan is made, also numbered week 1, nothing in it yet.
  const next = await resolveWeekPlan(db, block.id, 1, MON + 7, 1794420573, { autoGenerated: true })
  // Thursday: the night's back-fill, then Today and Program.
  installClock(Date.UTC(2026, 10, 12, 13, 0))
  await backfillCurrentWeek(db, THU, 1794491234)
  await call('2026-11-12', 'POST', '/api/sessions/generate-today', { date: '2026-11-12' })

  const week = await db.select().from(sessions).where(and(gte(sessions.scheduledDate, MON), lte(sessions.scheduledDate, MON + 6)))
  assert.ok(week.length > 0, 'this week has sessions')
  assert.deepEqual(week.filter(s => (s.scheduledDate ?? 0) < WED).map(s => `${s.scheduledDate} ${s.label}`), [], 'a week built on Wednesday plans nothing on Monday or Tuesday')
  console.log('ok: a week built mid-week plans from that day on, nothing back-filled before it')

  const program = await call<{ weekNumber: number; week: { week: { id: string }; sessions: Array<{ scheduledDate: number | null }> } | null }>('2026-11-12', 'GET', '/api/program?date=2026-11-12')
  assert.equal(program.weekNumber, 1, 'still week 1: nothing key done yet')
  assert.ok(program.week, 'Program has a week')
  assert.notEqual(program.week!.week.id, next, 'not next week\'s empty plan')
  assert.ok(program.week!.sessions.length > 0, 'Program shows this week\'s sessions, not a week of rest')
  assert.ok(program.week!.sessions.every(s => s.scheduledDate != null && s.scheduledDate >= MON && s.scheduledDate <= MON + 6), 'every one in this calendar week')
  const current = await call<{ week: { id: string } } | null>('2026-11-12', 'GET', `/api/weeks/current?blockId=${block.id}&weekNumber=1&date=2026-11-12`)
  assert.equal(current?.week.id, program.week!.week.id, '/weeks/current reads the same week')
  const ahead = await call<{ week: { id: string }; sessions: unknown[] } | null>('2026-11-12', 'GET', `/api/weeks/current?blockId=${block.id}&weekNumber=2&date=2026-11-12`)
  assert.ok(ahead == null || ahead.sessions.length === 0, 'the week ahead is next calendar week, never this one')
  console.log('ok: Program finds the week by its dates when the week number repeats')
  const left = await db.select().from(sessions).where(eq(sessions.status, 'missed'))
  assert.equal(left.length, 0, 'nothing turned missed')

  // He restarts Block Zero in Program on Thursday (start today): a fresh block,
  // its first week from Thursday on, Strength A its first lift, TB's lead-in from here.
  const fresh = await call<{ id: string }>('2026-11-12', 'POST', '/api/blocks/block-zero', { today: '2026-11-12' })
  await call('2026-11-12', 'POST', '/api/weeks/generate', { blockId: fresh.id, weekNumber: 1, startDate: '2026-11-09', today: '2026-11-12' })
  const freshPlans = new Set((await db.select({ id: weekPlans.id }).from(weekPlans).where(eq(weekPlans.blockId, fresh.id))).map(r => r.id))
  const after = (await db.select().from(sessions).where(and(gte(sessions.scheduledDate, MON), lte(sessions.scheduledDate, MON + 6)))).filter(s => s.weekPlanId != null && freshPlans.has(s.weekPlanId))
  assert.ok(after.length > 0, 'the fresh week has sessions')
  assert.ok(after.every(s => (s.scheduledDate ?? 0) >= THU), 'nothing planned before the restart day')
  const lifts = after.filter(s => s.type === 'strength').sort((a, b) => (a.scheduledDate ?? 0) - (b.scheduledDate ?? 0))
  assert.ok(lifts.length > 0, 'the fresh week has a lift')
  assert.equal(lifts[0].label, 'Strength A', 'the first lift is Strength A')
  const p2 = await call<{ block: { id: string }; week: { sessions: Array<{ scheduledDate: number | null }> } | null }>('2026-11-12', 'GET', '/api/program?date=2026-11-12')
  assert.equal(p2.block.id, fresh.id)
  assert.ok((p2.week?.sessions.length ?? 0) > 0, 'Program shows the fresh week')
  const preview = await call<{ brain: { why: string[] } }>('2026-11-12', 'GET', `/api/sessions/${lifts[0].id}/strength-preview`)
  assert.ok(preview.brain.why.some(w => /work up/.test(w)) || JSON.stringify(preview).includes('Find your weight'), 'Strength A finds its weights: the TB lead-in')
  console.log(`ok: a Thursday restart plans from Thursday, first lift Strength A (${lifts.map(l => `${l.scheduledDate! - MON}:${l.label}`).join(', ')})`)
} finally {
  uninstallClock()
}
